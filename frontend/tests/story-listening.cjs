const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs/promises');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/Users/quanta/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const { createV2TestDb } = require('../../backend/__tests__/helpers/reportCoreV2Db');
const { signToken } = require('../../backend/middleware/auth');

test('choose listening, play completely, see one point, school rank and persistent history', {timeout:120000}, async t => {
  const cleanups = [];
  t.after(async () => { for (const cleanup of cleanups.reverse()) await cleanup(); });
  const db = await createV2TestDb({ after:cleanup => cleanups.push(cleanup) });
  const server = require('../../backend/app').createApp({pool:db.pool,schoolId:'1'}).listen(0);
  cleanups.push(() => new Promise(resolve => server.close(resolve)));
  await new Promise(resolve => server.once('listening',resolve));
  const webPort = 19496;
  const vite = spawn(process.execPath,[path.resolve(__dirname,'../node_modules/vite/bin/vite.js'),'--host','127.0.0.1','--port',String(webPort),'--strictPort'], {cwd:path.resolve(__dirname,'..'),env:{...process.env,VITE_API_TARGET:`http://127.0.0.1:${server.address().port}`},stdio:'ignore'});
  cleanups.push(() => vite.kill());
  for(let i=0;i<80;i++) {try {if((await fetch(`http://127.0.0.1:${webPort}`)).ok) break;}catch{} await new Promise(r=>setTimeout(r,100));}
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  cleanups.push(() => browser.close());
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response', async response => { if (response.status() >= 400 && response.url().includes('/listening/')) console.log('LISTENING_RESPONSE', response.status(), await response.text()); });
  const [[user]] = await db.pool.query('SELECT * FROM users WHERE id=3');
  await page.addInitScript(token=>localStorage.setItem('REPORT_CORE_TOKEN',token),signToken(user));
  const url = `http://127.0.0.1:${webPort}/#/student/stories?termId=1`;
  await page.goto(url);
  await page.getByRole('button',{name:'听故事',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'听故事',exact:true}).getAttribute('aria-pressed'),'true');
  const first = page.getByRole('button',{name:'选择故事：小蜗牛的时间表',exact:true});
  await first.waitFor();
  assert.equal(await page.locator('.listening-story-choice').count(),100);
  await first.click();
  const play = page.getByRole('button',{name:'播放故事',exact:true});
  await play.waitFor();
  await play.click();
  await page.getByRole('button',{name:'暂停播放',exact:true}).waitFor();
  await page.getByRole('button',{name:'暂停播放',exact:true}).click();
  assert.equal(Number((await db.pool.query("SELECT COUNT(*) n FROM evaluation_source_record WHERE event_type='LISTEN_COMPLETE'"))[0][0].n),0);
  await page.getByRole('button',{name:'继续播放',exact:true}).click({timeout:8000}).catch(async e => {console.log('PAUSED_PAGE', await page.locator('body').innerText());throw e;});
  let droppedCompletion = false;
  await page.route('**/listening/*/complete',async route => {
    if (droppedCompletion) return route.continue();
    droppedCompletion = true;
    await route.fetch();
    await route.abort('failed');
  });
  await page.getByRole('button',{name:'重试保存积分',exact:true}).waitFor({timeout:40000});
  assert.equal(Number((await db.pool.query("SELECT COUNT(*) n FROM evaluation_source_record WHERE event_type='LISTEN_COMPLETE'"))[0][0].n),1);
  await page.getByRole('button',{name:'重试保存积分',exact:true}).click();
  await page.getByText('完整收听已完成，听故事积分 +1',{exact:true}).waitFor({timeout:40000});
  await page.getByText('第 1 名',{exact:true}).first().waitFor();
  assert.equal(await page.locator('.listening-history-item').count(),1);
  assert.equal(Number((await db.pool.query("SELECT COUNT(*) n FROM evaluation_source_record WHERE event_type='LISTEN_COMPLETE'"))[0][0].n),1);
  await fs.mkdir(path.resolve(__dirname,'../../output/story-listening'),{recursive:true});
  await page.screenshot({path:path.resolve(__dirname,'../../output/story-listening/desktop.png'),fullPage:true});
  await page.reload();
  await page.getByRole('button',{name:'听故事',exact:true}).click();
  await page.locator('.listening-history-item').waitFor();
  await page.getByRole('button',{name:'选择故事：小蜗牛的时间表',exact:true}).click();
  await page.getByRole('button',{name:'播放故事',exact:true}).click();
  await page.getByRole('button',{name:'暂停播放',exact:true}).waitFor();
  assert.equal(Number((await db.pool.query("SELECT COUNT(*) n FROM evaluation_source_record WHERE event_type='LISTEN_COMPLETE'"))[0][0].n),1);
  // Switching stories must stop the previous audio and reset the new timeline.
  await page.getByRole('button',{name:'选择故事：会道歉的小熊',exact:true}).click();
  await page.getByRole('button',{name:'播放故事',exact:true}).waitFor();
  assert.equal(await page.locator('audio').evaluate(a=>a.paused && a.currentTime===0),true);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.resolve(__dirname,'../../output/story-listening/mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'写故事',exact:true}).click();
  assert.equal(await page.locator('.listening-workspace').count(),0);
  assert.deepEqual(errors,[]);
});
